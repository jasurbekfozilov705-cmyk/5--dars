def sport_tavsiyasi(maqsad):
  if maqsad == "Vazn tashlash":
    return "Kardio mashqlar:Yugurish,arqon sakrash va kam kaloriya parxez."
  elif maqsad == "Mushak chiqarish":
    return "Kuch mashqlari: Gantel, shtanga va oqsilga boy taomlar."
  elif maqsad == "Chidamlilik":
    return "Suzish, velosiped uchish va uzoq masofaga yugurish."
  elif maqsad == "Egiluvchanlik":
   return "Yoga va raqs mashqlari."
  else:
   return "Murabbiy yoki mutaxassis bilan maslahat qiling!"
def oqsil_hisoblagich(vazn,maqsad):
  if maqsad == "Mushak chiqarish":
    return vazn * 2.0 # Har 1 kg uchun 2g oqsil
  elif maqsad == "Vazn tashlash":
    return vazn * 1.6 # Har 1 kg uchun 1.6g oqsil
  else:
    return vazn * 1.2 # Standart holat uchun

# Foydalanuvchidan ma'lumotlarni so'rash
maqsad = input("Sportdan maqsadingizni kiriting (Vazn tashlash/ Mushak chiqarish /Chidamlilik / Egiluvchanlik):")
vazn = float(input("Vazningizni kiriting (kg):"))

# Natijalarni chiqarish
tavsiya = sport_tavsiyasi(maqsad)
kerakli_oqsil = oqsil_hisoblagich(vazn, maqsad)

print("\n--- SIZNING DASTURINGIZ ---")
print(tavsiya)
print(f"Kunlik iste'mol qilishingiz kerak bo'lgan oqsil miqdori: {kerakli_oqsil} gramm")